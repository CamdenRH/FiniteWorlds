package dev.lemma.finiteworlds.core.geography;

/**
 * Non-volcanic Cascade summit hierarchy.
 *
 * BACKGROUND_ALPINE represents the smaller summit population that keeps the
 * mountain belt geographically continuous between the denser high-mountain
 * massifs. Volcanic centers intentionally live outside this hierarchy.
 */
public enum CascadePeakClass {
    BACKGROUND_ALPINE,
    ALPINE,
    MAJOR_ALPINE,
    REGIONAL_SUMMIT
}
